"""Computational Chemistry Interoperability & FAIR Export Module.

Generates standard input files for external HPC quantum chemistry packages:
  - ORCA (.inp)
  - Gaussian (.gjf / .com)
  - Multi-frame XYZ trajectory ensemble (.xyz)
  - Reproducible FAIR Run Recipe metadata (.json)
"""

import os
import sys
import json
import platform
from datetime import datetime
from typing import Dict, Any, List, Optional
import rdkit
import psi4

from energyinator.models import ConformerResult, CalculationResult
from energyinator.geometry import parse_xyz


ORCA_SOLVENT_MAP = {
    "water": "water",
    "chloroform": "chloroform",
    "dmso": "dmso",
    "methanol": "methanol",
    "toluene": "toluene",
    "acetonitrile": "acetonitrile",
    "dcm": "dichloromethane",
    "thf": "thf",
    "ethanol": "ethanol"
}

GAUSSIAN_SOLVENT_MAP = {
    "water": "water",
    "chloroform": "chloroform",
    "dmso": "dmso",
    "methanol": "methanol",
    "toluene": "toluene",
    "acetonitrile": "acetonitrile",
    "dcm": "dichloromethane",
    "thf": "tetrahydrofuran",
    "ethanol": "ethanol"
}


def generate_orca_input(
    conf: ConformerResult,
    method: str = "b3lyp",
    basis: str = "def2-SVP",
    solvent: Optional[str] = None,
    charge: int = 0,
    multiplicity: int = 1,
    calc_type: str = "Opt Freq",
    nprocs: int = 8,
    maxcore_mb: int = 2000
) -> str:
    """Generates a complete, ready-to-run ORCA (.inp) calculation input file."""
    symbols, coords = parse_xyz(conf.xyz_optimized or conf.xyz_initial)
    
    # Method and dispersion formatting
    m = method.lower().strip()
    if m == "b3lyp":
        route_method = "B3LYP D3BJ"
    elif m == "wb97x-d":
        route_method = "wB97X-D3"
    elif m in ["pbe", "pbe0"]:
        route_method = "PBE0 D3BJ"
    elif m == "mp2":
        route_method = "RI-MP2"
    else:
        route_method = method.upper()

    solv_clean = solvent.lower().strip() if solvent else None
    cpc_str = ""
    if solv_clean and solv_clean in ORCA_SOLVENT_MAP:
        cpc_str = f"CPCM({ORCA_SOLVENT_MAP[solv_clean]})"

    route_line = f"! {route_method} {basis} {calc_type} {cpc_str}".strip()

    delta_e = conf.delta_dft_kcalmol if conf.delta_dft_kcalmol is not None else 0.0
    lines = [
        f"# ==========================================================",
        f"# ORCA Input generated by Energyinator Studio",
        f"# Conformer ID: {conf.conf_id} | Delta E: {delta_e:.2f} kcal/mol",
        f"# Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        f"# ==========================================================",
        route_line,
        f"%pal nprocs {nprocs} end",
        f"%maxcore {maxcore_mb}",
        "",
        f"* xyz {charge} {multiplicity}"
    ]

    for sym, (x, y, z) in zip(symbols, coords):
        lines.append(f"  {sym:<2} {x:14.8f} {y:14.8f} {z:14.8f}")

    lines.append("*")
    lines.append("")
    return "\n".join(lines)


def generate_gaussian_input(
    conf: ConformerResult,
    method: str = "b3lyp",
    basis: str = "6-31G(d)",
    solvent: Optional[str] = None,
    charge: int = 0,
    multiplicity: int = 1,
    calc_type: str = "opt freq",
    nprocs: int = 8,
    memory: str = "8GB",
    chk_filename: Optional[str] = None
) -> str:
    """Generates a complete, ready-to-run Gaussian (.gjf / .com) input file."""
    symbols, coords = parse_xyz(conf.xyz_optimized or conf.xyz_initial)
    
    if not chk_filename:
        chk_filename = f"conformer_{conf.conf_id}.chk"

    solv_clean = solvent.lower().strip() if solvent else None
    scrf_str = ""
    if solv_clean and solv_clean in GAUSSIAN_SOLVENT_MAP:
        scrf_str = f"scrf=(pcm,solvent={GAUSSIAN_SOLVENT_MAP[solv_clean]})"

    route = f"#p {method}/{basis} {calc_type} {scrf_str}".strip()

    delta_e = conf.delta_dft_kcalmol if conf.delta_dft_kcalmol is not None else 0.0
    lines = [
        f"%chk={chk_filename}",
        f"%nprocshared={nprocs}",
        f"%mem={memory}",
        route,
        "",
        f"Energyinator Conformer {conf.conf_id} Optimization (Delta E = {delta_e:.2f} kcal/mol)",
        "",
        f"{charge} {multiplicity}"
    ]

    for sym, (x, y, z) in zip(symbols, coords):
        lines.append(f"{sym:<2} {x:14.8f} {y:14.8f} {z:14.8f}")

    lines.append("")
    lines.append("")
    return "\n".join(lines)


def generate_multi_xyz_trajectory(
    conformers: List[ConformerResult],
    smiles: str = ""
) -> str:
    """Combines all conformers into a concatenated multi-frame XYZ trajectory file.
    
    Compatible with molecular viewers (PyMOL, VMD, ChimeraX, Avogadro) for ensemble visualization.
    """
    frames = []
    for rank, c in enumerate(conformers):
        xyz_body = c.xyz_optimized or c.xyz_initial
        if not xyz_body:
            continue
        symbols, coords = parse_xyz(xyz_body)
        natoms = len(symbols)
        e_h = c.dft_energy_hartree if c.dft_energy_hartree is not None else 0.0
        d_e = c.delta_dft_kcalmol if c.delta_dft_kcalmol is not None else 0.0
        pop = c.boltzmann_pop if c.boltzmann_pop is not None else 0.0
        comment = (
            f"Frame {rank} | Conf {c.conf_id} | "
            f"E = {e_h:.6f} Eh | "
            f"Delta E = {d_e:.2f} kcal/mol | "
            f"Pop = {pop:.1f}% | {smiles}"
        )
        lines = [str(natoms), comment]
        for sym, (x, y, z) in zip(symbols, coords):
            lines.append(f"{sym:<2} {x:14.8f} {y:14.8f} {z:14.8f}")
        frames.append("\n".join(lines))

    return "\n".join(frames) + "\n"


def generate_run_recipe(
    res: CalculationResult,
    extra_metadata: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Generates a FAIR-compliant, reproducible execution recipe capturing exact software versions and run parameters."""
    recipe = {
        "generator": "Energyinator Quantum Molecular Studio",
        "timestamp_iso": datetime.now().isoformat(),
        "platform": {
            "system": platform.system(),
            "release": platform.release(),
            "python_version": sys.version.split()[0],
            "rdkit_version": getattr(rdkit, "__version__", "unknown"),
            "psi4_version": getattr(psi4, "__version__", "unknown")
        },
        "target_molecule": {
            "smiles": res.smiles,
            "formal_charge": res.formal_charge,
            "spin_multiplicity": res.spin_multiplicity
        },
        "computational_parameters": {
            "method": res.method,
            "basis": res.basis,
            "force_field": res.force_field,
            "used_xtb": getattr(res, "used_xtb", False),
            "xtb_method": getattr(res, "xtb_method", None),
            "solvent": res.solvent,
            "has_frequencies": res.has_frequencies
        },
        "ensemble_results_summary": {
            "conformers_generated": res.total_generated,
            "conformers_filtered_ff": res.unique_ff,
            "conformers_calculated_dft": res.calculated_dft,
            "conformers_unique_dft": res.unique_dft,
            "ground_state_energy_hartree": res.min_energy_hartree,
            "ground_state_energy_kcalmol": res.min_energy_kcalmol,
            "delta_e_span_kcalmol": round(res.max_energy_kcalmol - res.min_energy_kcalmol, 3),
            "ensemble_dipole_debye": getattr(res, "ensemble_dipole_debye", None),
            "ensemble_gap_ev": getattr(res, "ensemble_gap_ev", None),
            "conformational_entropy_cal_mol_k": getattr(res, "conformational_entropy_cal_mol_k", None),
            "conformational_free_energy_kcalmol": getattr(res, "conformational_free_energy_kcalmol", None),
            "elapsed_seconds": res.elapsed_time
        }
    }
    if extra_metadata:
        recipe["custom_metadata"] = extra_metadata
    return recipe
